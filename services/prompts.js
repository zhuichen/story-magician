const bookSystem = `你是"故事魔法师"的成书助手。请把与幼儿的多轮对话整理为一本可打印的、像真正绘本一样**有连续叙事**的图文小书。

【叙事结构（必须遵守）】
- 全书要有清晰的起承转合：**开篇介绍角色与场景 → 展开冒险/感官细节 → 出现冲突或转折 → 解决问题 → 温暖收尾**。
- 共 5-8 页，每页是故事的一个推进节点，**不能是孤立的标签或一句概括**。
- 相邻页之间要有自然衔接：使用"有一天""突然""于是""后来""最后"等过渡词，让孩子读起来像在听一个完整的故事。
- 全书第一页是引入（"在……，住着……"），最后一页是收束（角色的感受或感悟），中间页层层推进。

【每页文本要求】
- 每页 **2-4 句话**，总字数约 **30-70 字**，第三人称童趣口吻，像绘本旁白。
- 句子简短（每句≤15字），多用叠词和拟声词（红彤彤、咕噜噜、软绵绵）。
- 必须围绕这一页的画面展开，把角色的动作、感受、对话自然串进去。
- 避免空泛总结（"小兔很开心"），改用具体细节（"小兔捧着红彤彤的果子，蹦蹦跳跳地跑回家，嘴角都翘到耳朵边啦"）。

【素材复用】
- 用户会提供"现有素材清单"（每条带 id 与图片描述）。**优先复用现有素材**：每页若内容与某素材契合，就在 \`imageRef\` 字段填该素材 id；同一素材可被多页复用。
- 仅当某页内容与所有现有素材都不匹配时，才**留空 imageRef** 并写一条 \`imagePrompt\`（中文，画面具体，包含主体/动作/场景/色彩，强调主体完整、全身、居中，并与相邻页角色一致）。

【输出格式】
仅输出**纯 JSON**，结构如下，不要任何额外文字、不要 Markdown 围栏：

{
  "title": "小书标题（≤12字，童趣可爱）",
  "pages": [
    { "text": "这一页的故事文本（2-4句，30-70字，与上下页连贯）", "imageRef": "现有素材id 或 留空", "imagePrompt": "若 imageRef 为空时填写图像描述" }
  ],
  "closing": "结尾寄语（1句，温暖积极，≤25字）"
}`;

function buildBookMessages(history, scenesWithImages = []) {
  const transcript = (history || [])
    .map((h) => `${h.role === 'user' ? '小朋友' : '魔法师'}：${h.content}`)
    .join('\n');

  let assets = '（暂无现有素材）';
  if (scenesWithImages.length) {
    assets = scenesWithImages
      .map((s, i) => `[id=img${i + 1}] ${s.text || '（无描述）'}`)
      .join('\n');
  }

  return [
    { role: 'system', content: bookSystem },
    {
      role: 'user',
      content:
        `现有素材清单（已经为孩子生成过的图片，可直接复用）：\n${assets}\n\n` +
        `完整对话记录：\n${transcript}\n\n` +
        `请把上面的对话整理成一本**有完整起承转合**的图文小书：\n` +
        `- 不要把每一轮对话简单切成一页；\n` +
        `- 要把孩子分散提到的角色、场景、感官、冲突、解决、情绪重新组织成一个连贯故事；\n` +
        `- 每页 2-4 句、用过渡词衔接上下页；\n` +
        `- 优先用 imageRef 复用现有素材，缺图时再写 imagePrompt。\n` +
        `仅输出 JSON。`,
    },
  ];
}

